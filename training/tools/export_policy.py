"""Export a trained actor to the firmware contract and verify it against the simulator.

    .venv/bin/python tools/export_policy.py --actor runs/v1/actor.json --out artifacts/hover_balance_v1 --name hover_balance_v1

Writes   hover_policy_weights.h (float32 weights + input scaling), hover_policy.h (contract + inference),
         actor.json, test_vectors_*.txt (simulator ticks: sensor inputs -> expected commands), manifest.json
and      compiles tests/test_hover_policy.cpp with clang++ and replays the vectors through the C++ policy.
"""
import argparse
import os
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hover_sim.env import HoverEnv, make_config, OBS_DIM, ACT_DIM  # noqa: E402
from hover_sim.np_actor import NumpyActor  # noqa: E402
from hover_sim import plant as PL  # noqa: E402


def lit(x):
    """C float literal that is always valid (2 -> 2.0f, 1e-05 -> 1e-05f)."""
    s = f'{float(x):.9g}'
    if not any(c in s for c in '.en'):
        s += '.0'
    return s + 'f'


def c_array(name, a, ctype='float'):
    a = np.asarray(a, dtype=np.float32)
    if a.ndim == 1:
        body = ', '.join(lit(x) for x in a)
        return f'static const {ctype} {name}[{a.shape[0]}] = {{{body}}};\n'
    rows = ',\n    '.join('{' + ', '.join(lit(x) for x in r) + '}' for r in a)
    return f'static const {ctype} {name}[{a.shape[0]}][{a.shape[1]}] = {{\n    {rows}}};\n'


def write_weights_header(actor_json, path, name, steps):
    d = json.loads(Path(actor_json).read_text())
    L = d['layers']
    W = [np.array(l['W']) for l in L]
    B = [np.array(l['b']) for l in L]
    h = f'''// {name}: generated by tools/export_policy.py -- do not edit.
// network: obs({W[0].shape[1]}) -> tanh({W[0].shape[0]}) -> tanh({W[1].shape[0]}) -> linear({W[2].shape[0]}), inputs scaled by kHoverPolicyObsScale and clipped to +-5.
// trained steps: {steps}
#pragma once
namespace hover_rl {{
constexpr int kHoverPolicyObs = {W[0].shape[1]};
constexpr int kHoverPolicyH1 = {W[0].shape[0]};
constexpr int kHoverPolicyH2 = {W[1].shape[0]};
constexpr int kHoverPolicyAct = {W[2].shape[0]};
'''
    h += c_array('kHoverPolicyObsScale', d['obs_scale'])
    for i, (w, b) in enumerate(zip(W, B), 1):
        h += c_array(f'kHoverPolicyW{i}', w) + c_array(f'kHoverPolicyB{i}', b)
    h += '}  // namespace hover_rl\n'
    Path(path).write_text(h)


def record_vectors(actor, path, seed, domain, ticks, script=None):
    cfg = make_config()
    cfg.episode_s = 60.0
    env = HoverEnv(seed=seed, domain=domain, config=cfg, push_prob=1.0, corner_prob=0.0)
    obs, priv = env.reset(seed=seed, script=script)
    env.v_acc, env.r_acc = 0.3, 4.0       # the firmware wrapper uses fixed slew rates (training randomises them)
    rows = []
    for _ in range(ticks):
        a = actor.mean(obs)
        obs, priv, rew, term, trunc, info = env.step(a)
        if term:
            break
        raw = env._obs_raw.astype(np.float64)
        an = np.clip(actor.mean(obs), -1, 1)
        left = np.clip(an[0] - an[1], -1, 1) * 1000.0
        right = np.clip(an[0] + an[1], -1, 1) * 1000.0
        rows.append([info['tick'], raw[0], raw[1], raw[2], env.v_meas, info['vt'], info['rt'], raw[4], raw[5], raw[6], raw[7], raw[8],
                     an[0], an[1], left, right])
    np.savetxt(path, np.array(rows), fmt='%.9g')
    return len(rows), bool(env.fell)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--actor', required=True)
    ap.add_argument('--out', required=True)
    ap.add_argument('--name', default='hover_policy')
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    actor_json = json.loads(Path(args.actor).read_text())
    shutil.copy(args.actor, out / 'actor.json')
    write_weights_header(args.actor, out / 'hover_policy_weights.h', args.name, actor_json.get('trained_steps', 'unknown'))
    shutil.copy(ROOT.parent / 'main/boards/hover/hover_policy.h', out / 'hover_policy.h')
    shutil.copy(ROOT.parent / 'main/boards/hover/rl_controller.h', out / 'rl_controller.h')
    shutil.copy(ROOT / 'tests/test_hover_policy.cpp', out / 'test_hover_policy.cpp')
    actor = NumpyActor.from_json(args.actor)
    files = []
    n1, f1 = record_vectors(actor, out / 'test_vectors_1.txt', seed=11, domain=0.5, ticks=1800)
    scripted = dict(cmd=lambda t: ((0, 0), (0.15, 0), (0.15, 1.5), (-0.15, -1.5), (0, 2.0), (0, 0))[min(int(t // 2.0), 5)],
                    pushes=[(3.0, 0.3, 0.0, 0.05, 0.08), (7.0, -0.3, 0.0, 0.08, 0.08)])
    n2, f2 = record_vectors(actor, out / 'test_vectors_2.txt', seed=12, domain=1.0, ticks=1850, script=scripted)
    print(f'test vectors: {n1} ticks (fell={f1}), {n2} ticks (fell={f2})')
    exe = out / 'test_hover_policy'
    cmd = [os.environ.get('CXX', 'c++'), '-O2', '-std=c++17', '-I', str(out), str(out / 'test_hover_policy.cpp'), '-o', str(exe)]
    subprocess.run(cmd, check=True)
    r = subprocess.run([str(exe), str(out / 'test_vectors_1.txt'), str(out / 'test_vectors_2.txt')], capture_output=True, text=True)
    print(r.stdout.strip())
    ok = r.returncode == 0
    exe.unlink(missing_ok=True)
    sha = hashlib.sha256((out / 'hover_policy_weights.h').read_bytes()).hexdigest()
    manifest = dict(name=args.name, weights_sha256=sha, cpp_replay_ok=ok, trained_steps=actor_json.get('trained_steps'),
                    architecture=actor_json['architecture'], obs_scale=actor_json['obs_scale'],
                    note='cpp_replay_ok = C++ policy reproduces the simulator observation/command pipeline on recorded ticks')
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=1))
    print('C++ replay', 'OK' if ok else 'FAILED', ' weights sha256', sha[:16])
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
